/** 选文件后先确认合并；确认后才检查文件并执行导入，任何错误都提示导入失败。 */
const useHistoryImport = () => {
  const [file, setFile] = useState<File | null>(null)
  const [busy, setBusy] = useState(false)
  const [status, setStatus] = useState<Status>(null)
  const importing = useRef(false)

  const confirm = async () => {
    if (!file || importing.current) {
      return
    }
    importing.current = true
    setFile(null)
    setBusy(true)
    setStatus(null)
    try {
      const { inserted, updated, kept } = await importHistory(file)
      if (updated > 0 || kept > 0) {
        setStatus({
          key: 'historyImportedMerge',
          params: { count: inserted, updated, kept },
        })
      } else {
        setStatus({
          key: inserted === 1 ? 'historyImportedOne' : 'historyImported',
          params: { count: inserted },
        })
      }
    } catch {
      setStatus({ key: 'historyImportFailed', error: true })
    } finally {
      importing.current = false
      setBusy(false)
    }
  }

  return { file, busy, status, select: setFile, cancel: () => setFile(null), confirm }
}

/** 导入 = 合并：保留本地已有会话，同一会话按更新时间保留较新的版本。 */
const ImportHistory = ({
  historyImport,
  disabled,
}: {
  historyImport: ReturnType<typeof useHistoryImport>
  disabled: boolean
}) => {
  const t = useTranslate()
  const inputRef = useRef<HTMLInputElement>(null)

  return (
    <SettingCell
      label={t('historyImport')}
      description={t('historyImportDescription')}
      status={historyImport.status}
      action={
        <>
          <Button
            variant="outlined"
            size="m"
            className={clsx(styles.cellButton, styles.uploadButton)}
            disabled={disabled}
            onClick={() => inputRef.current?.click()}
          >
            <IconUploadOutline14 />
            {t('upload')}
          </Button>
          <input
            ref={inputRef}
            type="file"
            accept=".zip,application/zip,application/x-zip-compressed"
            hidden
            onChange={(event) => {
              const file = event.target.files?.[0]
              event.target.value = ''
              if (file) {
                historyImport.select(file)
              }
            }}
          />
        </>
      }
    />
  )
}

const downloadBlob = (name: string, blob: Blob) => {
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = name
  link.click()
  setTimeout(() => URL.revokeObjectURL(url), 10_000)
}

/** 将全部会话及图片导出为 ZIP 文件并下载 */
const ExportHistory = ({ disabled }: { disabled: boolean }) => {
  const t = useTranslate()
  const empty = useChatStore((state) => state.sessions.length === 0)
  const [busy, setBusy] = useState(false)
  const [status, setStatus] = useState<Status>(null)

  const onExport = async () => {
    setBusy(true)
    setStatus(null)
    try {
      const { name, blob } = await exportHistory()
      downloadBlob(name, blob)
    } catch (error) {
      setStatus(errorStatus('historyExportFailed', error))
    } finally {
      setBusy(false)
    }
  }

  return (
    <SettingCell
      label={t('exportAllLabel')}
      description={t('historyExportDescription')}
      status={status}
      action={
        <Button
          variant="outlined"
          size="m"
          className={styles.cellButton}
          disabled={disabled || busy || empty}
          onClick={() => void onExport()}
        >
          <IconDownloadOutline16 />
          {t('exportAllDownload')}
        </Button>
      }
    />
  )
}

/** 导出最近 72 小时内更新的会话 */
const ExportRecentHistory = ({ disabled }: { disabled: boolean }) => {
  const t = useTranslate()
  const empty = useChatStore(
    (state) =>
      !state.sessions.some(
        (session) => session.updatedAt >= Date.now() - RECENT_HISTORY_HOURS * 60 * 60 * 1000
      )
  )
  const [busy, setBusy] = useState(false)
  const [status, setStatus] = useState<Status>(null)

  const onExport = async () => {
    setBusy(true)
    setStatus(null)
    try {
      const { name, blob } = await exportHistory({ hours: RECENT_HISTORY_HOURS })
      downloadBlob(name, blob)
    } catch (error) {
      setStatus(errorStatus('historyExportFailed', error))
    } finally {
      setBusy(false)
    }
  }

  return (
    <SettingCell
      label={t('exportRecentLabel')}
      description={t('exportRecentDescription')}
      status={status}
      action={
        <Button
          variant="outlined"
          size="m"
          className={styles.cellButton}
          disabled={disabled || busy || empty}
          onClick={() => void onExport()}
        >
          <IconDownloadOutline16 />
          {t('exportAllDownload')}
        </Button>
      }
    />
  )
}

const useSyncHistory = () => {
  const serverUrl = useSettings((state) => state.syncServerUrl)
  const fileId = useSettings((state) => state.syncFileId)
  const [busy, setBusy] = useState(false)
  const [status, setStatus] = useState<Status>(null)
  const syncing = useRef(false)
  const valid = isValidSyncServerUrl(serverUrl) && isValidSyncFileId(fileId)

  const run = async () => {
    if (!valid || syncing.current) {
      return
    }
    syncing.current = true
    setBusy(true)
    setStatus(null)
    try {
      const result = await syncHistory({
        serverUrl: serverUrl.trim(),
        fileId: fileId.trim(),
        hours: RECENT_HISTORY_HOURS,
      })
      setStatus(
        result.uploaded
          ? {
              key: 'syncHistoryDone',
              params: {
                inserted: result.imported?.inserted ?? 0,
                updated: result.imported?.updated ?? 0,
                kept: result.imported?.kept ?? 0,
                exported: result.exported,
              },
            }
          : { key: 'syncHistoryNothing' }
      )
    } catch (error) {
      setStatus(
        error instanceof SyncUploadError
          ? { key: 'syncHistoryUploadFailed', params: { count: error.exported }, error: true }
          : { key: 'syncHistoryFailed', error: true }
      )
    } finally {
      syncing.current = false
      setBusy(false)
    }
  }

  return {
    serverUrl,
    fileId,
    valid,
    busy,
    status,
    run,
    setServerUrl: setSyncServerUrl,
    setFileId: setSyncFileId,
  }
}

/** 同步最近 3 天对话：拉取云端并合并，再覆盖上传本地快照。 */
const SyncHistory = ({
  sync,
  disabled,
}: {
  sync: ReturnType<typeof useSyncHistory>
  disabled: boolean
}) => {
  const t = useTranslate()
  const { status } = sync
  const invalid = !sync.valid && (sync.serverUrl.trim() !== '' || sync.fileId.trim() !== '')

  return (
    <div className={styles.cell}>
      <div className={styles.row}>
        <div className={styles.text}>
          <div className={styles.label}>{t('syncHistory')}</div>
          <div className={clsx(styles.description, (status?.error || invalid) && styles.error)}>
            {status
              ? t(status.key, status.reason ? { message: t(status.reason) } : status.params)
              : invalid
                ? t('syncHistoryInvalidConfig')
                : t('syncHistoryDescription')}
          </div>
        </div>
        <Button
          variant="outlined"
          size="m"
          className={styles.cellButton}
          disabled={disabled || !sync.valid}
          onClick={() => void sync.run()}
        >
          {sync.busy ? t('syncing') : t('syncNow')}
        </Button>
      </div>
      <div className={styles.syncInputs}>
        <label className={styles.syncField}>
          <span>{t('syncServerUrl')}</span>
          <input
            type="url"
            inputMode="url"
            placeholder={t('syncServerUrlPlaceholder')}
            autoComplete="off"
            spellCheck={false}
            value={sync.serverUrl}
            disabled={disabled}
            onChange={(event) => sync.setServerUrl(event.target.value)}
          />
        </label>
        <label className={styles.syncField}>
          <span>{t('syncFileId')}</span>
          <input
            type="text"
            placeholder={t('syncFileIdPlaceholder')}
            autoComplete="off"
            spellCheck={false}
            value={sync.fileId}
            disabled={disabled}
            onChange={(event) => sync.setFileId(event.target.value)}
          />
        </label>
      </div>
    </div>
  )
}
